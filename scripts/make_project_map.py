"""Write docs/project_map.md: an up-to-date inventory of the code, tests, docs and data tables.

Run from the repo root with the `nhl` conda environment active:

    python scripts/make_project_map.py

The map is generated from the repo itself (nothing is typed by hand), so it cannot drift from the code.
For every Python file under src/, scripts/ and tests/: the first line of its docstring, its top-level
functions and classes (tests: how many tests). For docs/: the title. For data/: every parquet table by
layer, with row counts per season and the columns. Attach the file at the start of a working session
so that new code starts from what already exists.
"""

import ast
import re
from pathlib import Path

import pyarrow.parquet as pq

REPO_ROOT = Path(__file__).resolve().parents[1]
CODE_FOLDERS = ("src", "scripts", "tests")
DATA_LAYERS = ("staging", "intermediate", "metrics")
OUTPUT = REPO_ROOT / "docs" / "project_map.md"
SKIP_PARTS = {"__pycache__", ".git", ".venv", "node_modules"}


def first_line(text):
    """First non-empty line of a docstring, or ''."""
    for line in (text or "").splitlines():
        if line.strip():
            return line.strip()
    return ""


def describe_python_file(path):
    """{'purpose', 'functions', 'classes', 'tests'} for one Python file, read without importing it."""
    tree = ast.parse(Path(path).read_text(encoding="utf-8"))
    functions = [n.name for n in tree.body if isinstance(n, ast.FunctionDef)]
    return {
        "purpose": first_line(ast.get_docstring(tree)),
        "functions": [name for name in functions if not name.startswith("test_")],
        "classes": [n.name for n in tree.body if isinstance(n, ast.ClassDef)],
        "tests": sum(1 for name in functions if name.startswith("test_")),
    }


def markdown_title(path):
    """First heading of a markdown file, or its file name."""
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        match = re.match(r"#+\s+(.*)", line)
        if match:
            return match.group(1).strip()
    return Path(path).name


def python_files(folder):
    return sorted(p for p in Path(folder).rglob("*.py") if not SKIP_PARTS & set(p.parts) and p.name != "__init__.py")


def render_code_section(root, folder):
    lines = [f"## {folder}/", ""]
    for path in python_files(root / folder):
        info = describe_python_file(path)
        relative = path.relative_to(root).as_posix()
        lines.append(f"### `{relative}`")
        if info["purpose"]:
            lines.append(info["purpose"])
        if info["tests"]:
            lines.append(f"- tests: {info['tests']}")
        if info["classes"]:
            lines.append("- classes: " + ", ".join(f"`{n}`" for n in info["classes"]))
        if info["functions"]:
            lines.append("- functions: " + ", ".join(f"`{n}`" for n in info["functions"]))
        lines.append("")
    return lines


def table_summary(path):
    """(rows, columns) of one parquet file, from its metadata only."""
    parquet = pq.ParquetFile(path)
    return parquet.metadata.num_rows, parquet.schema_arrow.names


def render_data_section(root):
    lines = ["## data tables (parquet)", ""]
    data = root / "data"
    for layer in DATA_LAYERS:
        tables = {}
        for path in sorted((data / layer).glob("season=*/*.parquet")) if (data / layer).exists() else []:
            season = path.parent.name.replace("season=", "")
            tables.setdefault(path.stem, {})[season] = path
        if not tables:
            continue
        lines += [f"### {layer}", ""]
        for name, by_season in sorted(tables.items()):
            rows = {season: table_summary(path)[0] for season, path in sorted(by_season.items())}
            columns = table_summary(by_season[max(by_season)])[1]
            counts = ", ".join(f"{season}: {n:,}" for season, n in rows.items())
            lines.append(f"- `{name}` ({counts} rows)")
            lines.append(f"  columns: {', '.join(columns)}")
        lines.append("")
    return lines


def render_docs_section(root):
    lines = ["## docs/", ""]
    for path in sorted((root / "docs").glob("*.md")):
        if path.name != OUTPUT.name:
            lines.append(f"- `docs/{path.name}`: {markdown_title(path)}")
    lines.append("")
    return lines


def build_map(root):
    lines = [
        "# Project map",
        "",
        "Generated by `scripts/make_project_map.py`. Do not edit by hand; run the script again.",
        "Before writing new code, check here for what already exists.",
        "",
    ]
    for folder in CODE_FOLDERS:
        if (root / folder).exists():
            lines += render_code_section(root, folder)
    lines += render_docs_section(root)
    lines += render_data_section(root)
    return "\n".join(lines) + "\n"


def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    text = build_map(REPO_ROOT)
    OUTPUT.write_text(text, encoding="utf-8")
    code_files = sum(len(python_files(REPO_ROOT / folder)) for folder in CODE_FOLDERS if (REPO_ROOT / folder).exists())
    print(f"Wrote {OUTPUT} ({len(text.splitlines())} lines, {code_files} Python files)")


if __name__ == "__main__":
    main()
