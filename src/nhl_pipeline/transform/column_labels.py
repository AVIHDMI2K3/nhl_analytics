def label(column):
    return LABELS[column]


def description(table, column):
    return OVERRIDES.get(table, {}).get(column) or DESCRIPTIONS[column]


def all_columns(table):
    """Every column in the table's file, in the order: fixed, grouped, hidden."""
    return list(FIXED[table]) + [c for _, cols in GROUPS[table] for c in cols] + list(HIDDEN[table])


def visible_groups(table, selected=None):
    """Groups of columns as [(group label, [column, ...])].

    Uses the columns in `selected` (default: DEFAULTS[table]); groups with none left are left out."""
    chosen = set(DEFAULTS[table] if selected is None else selected)
    shown = [(group, [c for c in cols if c in chosen]) for group, cols in GROUPS[table]]
    return [(group, cols) for group, cols in shown if cols]
